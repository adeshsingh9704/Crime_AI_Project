from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    PageBreak
)

from modules.hotspot import (
    load_crime_data,
    get_hotspots,
    get_statistics
)


def generate_report(output_file="reports/report.pdf"):
    """
    Generate a professional Crime AI PDF report.
    """

    # ---------------------------------------------------------
    # Load data
    # ---------------------------------------------------------

    df = load_crime_data()
    hotspots = get_hotspots()
    statistics = get_statistics()

    # ---------------------------------------------------------
    # Create PDF
    # ---------------------------------------------------------

    document = SimpleDocTemplate(
        output_file,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "TitleCustom",
        parent=styles["Title"],
        alignment=TA_CENTER,
        fontSize=22,
        spaceAfter=20
    )

    heading_style = ParagraphStyle(
        "HeadingCustom",
        parent=styles["Heading2"],
        fontSize=15,
        spaceBefore=15,
        spaceAfter=10
    )

    body_style = ParagraphStyle(
        "BodyCustom",
        parent=styles["BodyText"],
        fontSize=10,
        leading=15,
        spaceAfter=8
    )

    story = []

    # ---------------------------------------------------------
    # TITLE
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "Crime AI Analytics System",
            title_style
        )
    )

    story.append(
        Paragraph(
            "Geospatial Crime Analysis and AI-Assisted Dashboard",
            styles["Heading3"]
        )
    )

    story.append(Spacer(1, 20))

    story.append(
        Paragraph(
            "This report summarizes the analytical outputs "
            "generated by the Crime AI educational prototype.",
            body_style
        )
    )

    # ---------------------------------------------------------
    # PROJECT OVERVIEW
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "1. Project Overview",
            heading_style
        )
    )

    story.append(
        Paragraph(
            "The Crime AI project combines geospatial clustering, "
            "crime-type prediction, legal text similarity, "
            "computer-vision image comparison and a Flask-based "
            "web dashboard.",
            body_style
        )
    )

    # ---------------------------------------------------------
    # DATASET SUMMARY
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "2. Crime Dataset Summary",
            heading_style
        )
    )

    summary_data = [
        ["Metric", "Value"],
        [
            "Total crime records",
            str(statistics["total_records"])
        ],
        [
            "Detected spatial clusters",
            str(statistics["hotspot_count"])
        ],
        [
            "Records inside clusters",
            str(statistics["records_in_hotspots"])
        ]
    ]

    table = Table(
        summary_data,
        colWidths=[280, 150]
    )

    table.setStyle(
        TableStyle([
            (
                "BACKGROUND",
                (0, 0),
                (-1, 0),
                colors.lightgrey
            ),
            (
                "GRID",
                (0, 0),
                (-1, -1),
                0.5,
                colors.grey
            ),
            (
                "FONTNAME",
                (0, 0),
                (-1, 0),
                "Helvetica-Bold"
            ),
            (
                "ALIGN",
                (1, 1),
                (-1, -1),
                "CENTER"
            ),
            (
                "VALIGN",
                (0, 0),
                (-1, -1),
                "MIDDLE"
            )
        ])
    )

    story.append(table)

    # ---------------------------------------------------------
    # CRIME DISTRIBUTION
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "3. Crime Type Distribution",
            heading_style
        )
    )

    distribution = statistics[
        "crime_distribution"
    ]

    distribution_data = [
        ["Crime Type", "Number of Records"]
    ]

    for crime_type, count in distribution.items():

        distribution_data.append([
            str(crime_type),
            str(count)
        ])

    distribution_table = Table(
        distribution_data,
        colWidths=[280, 150]
    )

    distribution_table.setStyle(
        TableStyle([
            (
                "BACKGROUND",
                (0, 0),
                (-1, 0),
                colors.lightgrey
            ),
            (
                "GRID",
                (0, 0),
                (-1, -1),
                0.5,
                colors.grey
            ),
            (
                "FONTNAME",
                (0, 0),
                (-1, 0),
                "Helvetica-Bold"
            ),
            (
                "ALIGN",
                (1, 1),
                (-1, -1),
                "CENTER"
            )
        ])
    )

    story.append(distribution_table)

    # ---------------------------------------------------------
    # HOTSPOT ANALYSIS
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "4. Geospatial Hotspot Analysis",
            heading_style
        )
    )

    story.append(
        Paragraph(
            "DBSCAN clustering is used to identify groups of "
            "nearby geographic crime records. Cluster labels "
            "represent spatial groupings and should not be "
            "interpreted as proof that an area or person is "
            "dangerous.",
            body_style
        )
    )

    if hotspots:

        hotspot_data = [
            [
                "Cluster",
                "Latitude",
                "Longitude",
                "Records"
            ]
        ]

        for hotspot in hotspots:

            hotspot_data.append([
                str(
                    hotspot["cluster_id"]
                ),
                f'{hotspot["latitude"]:.5f}',
                f'{hotspot["longitude"]:.5f}',
                str(
                    hotspot["crime_count"]
                )
            ])

        hotspot_table = Table(
            hotspot_data,
            colWidths=[
                80,
                110,
                110,
                100
            ]
        )

        hotspot_table.setStyle(
            TableStyle([
                (
                    "BACKGROUND",
                    (0, 0),
                    (-1, 0),
                    colors.lightgrey
                ),
                (
                    "GRID",
                    (0, 0),
                    (-1, -1),
                    0.5,
                    colors.grey
                ),
                (
                    "FONTNAME",
                    (0, 0),
                    (-1, 0),
                    "Helvetica-Bold"
                ),
                (
                    "ALIGN",
                    (0, 0),
                    (-1, -1),
                    "CENTER"
                )
            ])
        )

        story.append(hotspot_table)

    else:

        story.append(
            Paragraph(
                "No spatial clusters were detected "
                "using the current clustering parameters.",
                body_style
            )
        )

    # ---------------------------------------------------------
    # TECHNOLOGY
    # ---------------------------------------------------------

    story.append(
        PageBreak()
    )

    story.append(
        Paragraph(
            "5. Technologies Used",
            heading_style
        )
    )

    technologies = [
        "Python",
        "Flask",
        "Pandas",
        "NumPy",
        "Scikit-learn",
        "DBSCAN",
        "Random Forest",
        "TF-IDF and cosine similarity",
        "OpenCV",
        "ReportLab",
        "Leaflet-based interactive mapping"
    ]

    for technology in technologies:

        story.append(
            Paragraph(
                "• " + technology,
                body_style
            )
        )

    # ---------------------------------------------------------
    # LIMITATIONS
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "6. Limitations",
            heading_style
        )
    )

    limitations = [
        "The demonstration crime dataset is very small.",
        "Historical geographic clustering does not establish "
        "that future crime will occur at a location.",
        "Browser GPS provides the user's current coordinates; "
        "it does not provide a live government crime feed.",
        "The crime prediction component is an educational "
        "prototype and requires larger validated datasets "
        "for meaningful evaluation.",
        "Image comparison does not establish a person's identity.",
        "Legal similarity results are information retrieval "
        "outputs and are not legal advice or predictions "
        "of case outcomes."
    ]

    for limitation in limitations:

        story.append(
            Paragraph(
                "• " + limitation,
                body_style
            )
        )

    # ---------------------------------------------------------
    # FUTURE SCOPE
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "7. Future Scope",
            heading_style
        )
    )

    future_scope = [
        "Larger and validated crime datasets.",
        "Time-based crime trend analysis.",
        "Interactive filtering by crime category.",
        "Historical heatmaps.",
        "Improved model evaluation with train/test validation.",
        "Authorized and verified live incident data feeds.",
        "Improved privacy and security controls.",
        "Audit logging and human review for consequential use."
    ]

    for item in future_scope:

        story.append(
            Paragraph(
                "• " + item,
                body_style
            )
        )

    # ---------------------------------------------------------
    # CONCLUSION
    # ---------------------------------------------------------

    story.append(
        Paragraph(
            "8. Conclusion",
            heading_style
        )
    )

    story.append(
        Paragraph(
            "The Crime AI prototype demonstrates how machine "
            "learning, geospatial analysis, natural-language "
            "processing and computer vision can be combined "
            "with a web dashboard to analyze a small crime "
            "dataset. The outputs are intended for educational "
            "and analytical demonstration rather than "
            "automated decisions about individuals.",
            body_style
        )
    )

    # ---------------------------------------------------------
    # BUILD PDF
    # ---------------------------------------------------------

    document.build(story)

    return output_file